const GENERIC_FAMILIES = new Set(["serif", "sans-serif", "monospace", "system-ui", "ui-monospace"]);

function leaves(node, path = [], type) {
  const out = [];
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith("$")) continue;
    const here = value.$type ?? type;
    if ("$value" in value) out.push({ path: [...path, key], type: here, value: value.$value });
    else out.push(...leaves(value, [...path, key], here));
  }
  return out;
}

function css(type, value) {
  if (type === "fontFamily")
    return value
      .map((name) =>
        name.includes(" ") || (!GENERIC_FAMILIES.has(name) && /[^a-z-]/i.test(name)) ? `"${name}"` : name,
      )
      .join(", ");
  if (type === "cubicBezier") return `cubic-bezier(${value.join(", ")})`;
  return String(value);
}

/** Renders tokens.css: shared tokens on :root, and each theme's semantic colours under [data-theme]. */
export function buildCss(tokens) {
  const all = leaves(tokens);
  const shared = all.filter((token) => !(token.path[0] === "color" && token.path[1] === "theme"));
  const themes = all.filter((token) => token.path[0] === "color" && token.path[1] === "theme");
  const lines = ["/* Generated by tools/build-tokens.mjs from brand/tokens.json. Do not edit. */"];
  lines.push(":root {");
  for (const token of shared) lines.push(`  --dc-${token.path.join("-")}: ${css(token.type, token.value)};`);
  lines.push("}");
  const names = [...new Set(themes.map((token) => token.path[2]))];
  names.forEach((name, index) => {
    const selector = index === 0 ? `:root,\n[data-theme="${name}"]` : `[data-theme="${name}"]`;
    lines.push("", `${selector} {`);
    for (const token of themes.filter((entry) => entry.path[2] === name)) {
      lines.push(`  --dc-${token.path.slice(3).join("-")}: ${css(token.type, token.value)};`);
    }
    lines.push("}");
  });
  return `${lines.join("\n")}\n`;
}
